import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { Client } from '@modelcontextprotocol/sdk/client/index.js';
import { StreamableHTTPClientTransport } from '@modelcontextprotocol/sdk/client/streamableHttp.js';
import { createService } from './server.mjs';
import { createCore } from './core.mjs';
const here = path.dirname(fileURLToPath(import.meta.url));
test('MCP generation, proposal preview, version conflict, browser API and durable history', async () => {
  const root = path.resolve(here, '../..');
  const storage = fs.mkdtempSync(path.join(here, '.service-test-'));
  const config = { host: '127.0.0.1', publicUrl: 'http://127.0.0.1:1', token: 'test-token-only', dataDir: storage, workspaceRoot: root, toolkitDir: path.join(root, 'releases/monthly-toolkit-portable') };
  const { server } = createService(config);
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  const url = `http://127.0.0.1:${server.address().port}`;
  config.publicUrl = url;
  const client = new Client({ name: 'monthly-service-test', version: '1' });
  const transport = new StreamableHTTPClientTransport(new URL(url + '/mcp'), { requestInit: { headers: { Authorization: 'Bearer test-token-only' } } });
  const headers = { Authorization: 'Bearer test-token-only', 'Content-Type': 'application/json' };
  const call = async (name, args) => { const response = await client.callTool({ name, arguments: args }); return { result: JSON.parse(response.content[0].text), isError: response.isError }; };
  try {
    assert.equal((await fetch(url + '/api/tools')).status, 401);
    const uiStyle=await fetch(url+'/ui/dashboard.css');assert.equal(uiStyle.status,200);assert.match(uiStyle.headers.get('content-type'),/text\/css/);
    const uiScript=await fetch(url+'/ui/dashboard.js');assert.equal(uiScript.status,200);assert.match(uiScript.headers.get('content-type'),/javascript/);
    assert.equal((await fetch(url+'/api/projects',{headers:{}})).status,401,'public UI assets must not expose protected APIs');
    assert.equal((await fetch(url+'/api/templates/import-pptx',{method:'POST',headers:{'Content-Type':'application/json'},body:'{}'})).status,401,'PPT template uploads require authentication');
    assert.equal((await fetch(url+'/api/templates/import-pptx',{method:'POST',headers,body:'{}'})).status,400,'invalid uploads must not create a template');
    assert.equal((await fetch(url + '/api/tools', { headers: { ...headers, Origin: 'https://untrusted.example' } })).status, 403);
    await client.connect(transport);
    const availableTools=(await client.listTools()).tools;assert.ok(availableTools.length>=42);
    assert.ok(availableTools.some(t=>t.name==='get_template_ai_task'));assert.ok(availableTools.some(t=>t.name==='submit_template_ai_task'));
    assert.ok(availableTools.some(t=>t.name==='get_template_data_sources'));assert.ok(availableTools.some(t=>t.name==='configure_template_data_sources'));
    const data = JSON.parse(fs.readFileSync(path.join(here, 'demo/monthly-report-2026-08.json')));
    const task = (await call('generate_monthly_report', { month: '2026-08', data, profile:'data-supported' })).result;
    let state;
    for (let i = 0; i < 100; i++) { state = (await call('get_task', { taskId: task.id })).result; if (state.status !== 'running') break; await new Promise(resolve => setTimeout(resolve, 50)); }
    assert.equal(state.status, 'succeeded', state.error);
    const id = state.projectId;
    const before = (await call('get_project', { projectId: id, pageIndex: 0 })).result;
    const object = before.pages[0].objects.find(o => o.content.includes('Steam8月月报'));
    assert.ok(object);
    const change = { id: object.attributes['data-object-id'], content: object.content.replace('Steam8月月报', 'MCP验收月报') };
    const proposal = (await call('propose_object_patch', { projectId: id, baseRevision: 1, requirement: '更新标题', changes: [change] })).result;
    const stale = (await call('propose_object_patch', { projectId: id, baseRevision: 1, changes: [{ id: change.id, style: { color: '#123456' } }] })).result;
    assert.equal((await call('get_project', { projectId: id })).result.revision, 1);
    const preview = await fetch(proposal.preview, { headers }); assert.equal(preview.status, 200); assert.match(await preview.text(), /MCP验收月报/);
    assert.equal((await call('apply_proposal', { proposalId: proposal.id })).result.revision, 2);
    const conflict = await call('apply_proposal', { proposalId: stale.id }); assert.equal(conflict.isError, true); assert.equal(conflict.result.status, 409);
    const value = await (await fetch(url + '/api/projects/' + id, { headers })).json(); assert.equal(value.revision, 2);
    const restored = createCore(config); assert.equal(restored.project(id).revision, 2);
    const imported = await (await fetch(url + '/api/import', { method: 'POST', headers, body: JSON.stringify(value) })).json();
    assert.notEqual(imported.projectId, id, 'import editable archive as a new project');
    const importedValue = await (await fetch(url + '/api/projects/' + imported.projectId, { headers })).json();
    assert.equal(importedValue.revision, 1);
    assert.deepEqual(importedValue.project, value.project);
    assert.equal((await fetch(url + '/api/import', { method: 'POST', headers, body: JSON.stringify({ project: {} }) })).status, 400);
    const demo = await (await fetch(url + '/api/demo', { method: 'POST', headers, body: '{}' })).json();
    let demoState;
    for (let i=0;i<120;i++) { demoState=(await call('get_task',{taskId:demo.id})).result; if(demoState.status!=='running')break; await new Promise(resolve=>setTimeout(resolve,50)); }
    assert.equal(demoState.status, 'succeeded', demoState.error);
    const demoProject = (await call('get_project', {projectId:demoState.projectId})).result;
    assert.ok(demoProject.pages.length >= 8);
    const health = await (await fetch(url + '/api/health', {headers})).json();
    assert.equal(health.service, 'ok');
    assert.equal(health.onlineGenerationConfigured, false);
    const html = await fetch(url + `/api/projects/${id}/export.html`, { headers }); assert.match(await html.text(), /MCP验收月报/);
    const editor = await fetch(url + '/editor?project=' + id, { headers, redirect: 'manual' }); assert.equal(editor.status, 302); assert.match(editor.headers.get('location'), /ui=native/);
    const silex = await (await fetch(url + `/api/projects/${id}/silex`, { headers })).json(); assert.equal(silex.revision, 2); assert.equal(silex.editorData.pages.length, 5);
    const request = await (await fetch(url + `/api/projects/${id}/ai-requests`, { method: 'POST', headers, body: JSON.stringify({ baseRevision: 2, objectIds: [change.id], requirement: '修改这里' }) })).json();
    assert.equal((await call('get_ai_request', { requestId: request.id })).result.requirement, '修改这里');
    assert.deepEqual((await call('list_versions', { projectId: id })).result.revisions, [1]);
    assert.ok(fs.readdirSync(path.join(storage, 'conflicts')).length);
    const nativeProject = { ...value.project, silexState: silex.editorData };
    const nativeSave = await fetch(url + '/api/projects/' + id, { method: 'PUT', headers, body: JSON.stringify({ baseRevision: 2, project: nativeProject, author: 'silex-operator' }) });
    assert.equal((await nativeSave.json()).revision, 3);
    const nativeResponse = await fetch(url + `/api/projects/${id}/silex`, { headers: { ...headers, 'Accept-Encoding': 'gzip', Origin: 'http://localhost:6805' } });
    assert.equal(nativeResponse.headers.get('content-encoding'), 'gzip');
    assert.match(nativeResponse.headers.get('vary'), /Origin/);
    assert.match(nativeResponse.headers.get('vary'), /Accept-Encoding/);
    const compactNative = await nativeResponse.json();
    assert.equal(compactNative.project.silexState, undefined, 'do not duplicate editor state in the loading response');
    assert.deepEqual(compactNative.editorData, silex.editorData, 'retain the exact editable state');
    const identityResponse = await fetch(url + `/api/projects/${id}/silex`, { headers: { ...headers, 'Accept-Encoding': 'gzip;q=0' } });
    assert.equal(identityResponse.headers.get('content-encoding'), null);
    assert.deepEqual((await identityResponse.json()).editorData, compactNative.editorData);
    const persistedNative = await (await fetch(url + '/api/projects/' + id, { headers })).json();
    assert.deepEqual(persistedNative.project.silexState, silex.editorData, 'stored project remains editable');
    const nextProposal = (await call('propose_object_patch', { projectId: id, baseRevision: 3, requestId: request.id, changes: [{ id: change.id, content: change.content.replace('MCP验收月报', 'AI二次标题') }] })).result;
    assert.equal((await call('get_ai_request', { requestId: request.id })).result.status, 'proposed');
    assert.equal(nextProposal.requirement, request.requirement);
    const crossProject = await call('propose_object_patch', {projectId: imported.projectId, baseRevision: 1, requestId: request.id, changes: [change]});
    assert.equal(crossProject.isError, true, 'never associate another project request');
    const retryProposal = (await call('propose_object_patch', {projectId:id,baseRevision:3,requestId:request.id,changes:[change]})).result;
    assert.equal((await call('reject_proposal',{proposalId:retryProposal.id})).result.status,'rejected');
    assert.equal((await call('get_ai_request',{requestId:request.id})).result.status,'proposed','one pending proposal remains');
    assert.equal((await call('apply_proposal', { proposalId: nextProposal.id })).result.revision, 4);
    assert.equal((await call('get_ai_request',{requestId:request.id})).result.status,'applied');
    assert.equal((await call('list_ai_requests',{projectId:id})).result.length,0,'completed requests leave the default queue');
    assert.equal((await call('list_ai_requests',{projectId:id,status:'all'})).result.length,1);
    const afterAi = await (await fetch(url + '/api/projects/' + id, { headers })).json();
    assert.ok(afterAi.project.silexState, 'AI patch must retain native project metadata');
    const updatedNative = await (await fetch(url + `/api/projects/${id}/silex`, { headers })).json();
    assert.match(JSON.stringify(updatedNative.editorData), /AI二次标题/);
    const makeRequest = async () => (await (await fetch(url + `/api/projects/${id}/ai-requests`, { method:'POST',headers,body:JSON.stringify({baseRevision:4,objectIds:[change.id],requirement:'取消测试需求'})})).json());
    const cancelled=await makeRequest();
    const cancelledProposal=(await call('propose_object_patch',{projectId:id,baseRevision:4,requestId:cancelled.id,changes:[change]})).result;
    await call('reject_proposal',{proposalId:cancelledProposal.id});
    assert.equal((await call('get_ai_request',{requestId:cancelled.id})).result.status,'pending');
    const cancelledAgain=(await call('propose_object_patch',{projectId:id,baseRevision:4,requestId:cancelled.id,changes:[change]})).result;
    await call('cancel_ai_request',{requestId:cancelled.id});
    assert.equal((await call('apply_proposal',{proposalId:cancelledAgain.id})).isError,true);
    assert.equal((await call('get_project',{projectId:id})).result.revision,4,'reject/cancel never changes report content');
    const renamed=(await call('rename_project',{projectId:id,baseRevision:4,title:'  团队演示终稿  '})).result;
    assert.equal(renamed.revision,5);
    const renamedValue=await (await fetch(url+'/api/projects/'+id,{headers})).json();
    assert.equal(renamedValue.title,'团队演示终稿');
    assert.deepEqual(renamedValue.project,afterAi.project,'renaming preserves all editable contents');
    assert.equal((await call('rename_project',{projectId:id,baseRevision:4,title:'过期名称'})).result.status,409);
    assert.equal((await call('rename_project',{projectId:id,baseRevision:5,title:' '})).isError,true);
    const browserRequests=await (await fetch(url+`/api/projects/${id}/ai-requests`,{headers})).json();
    assert.equal(browserRequests.length,2);
    const presence = async dirty => fetch(url+`/api/projects/${id}/editor-context`,{method:'POST',headers,body:JSON.stringify({sessionId:'mcp-browser',pageIndex:0,objectIds:[change.id],focused:true,dirty})});
    assert.equal((await presence(true)).status,200);
    assert.equal((await call('get_editing_context')).result.projectId,id);
    const directArgs={projectId:id,baseRevision:5,requirement:'聊天直接调整颜色',changes:[{id:change.id,style:{color:'#123455'}}]};
    assert.equal((await call('apply_object_patch',directArgs)).result.status,409);
    await presence(false);
    assert.equal((await call('apply_object_patch',directArgs)).result.revision,6);
    assert.equal((await call('restore_project_version',{projectId:id,baseRevision:6,targetRevision:5})).result.revision,7);
    const expired = structuredClone(data);
    expired.issues.push({ code: 'head_revenue_incomplete', message: 'DataBrain JWT 已过期' });
    const stopped = (await call('generate_monthly_report', { month: '2026-08', data: expired, profile: 'data-supported' })).result;
    let paused;
    for (let i=0;i<60;i++) { paused=(await call('get_task',{taskId:stopped.id})).result; if(paused.status!=='running')break; await new Promise(resolve=>setTimeout(resolve,50)); }
    assert.equal(paused.status,'awaiting_credentials');
    assert.equal(paused.projectId,undefined,'never publish an empty draft on expired credentials');
  } finally {
    await client.close(); await new Promise(resolve => server.close(resolve));
    const absolute = path.resolve(storage); if (!absolute.startsWith(here + path.sep) || !path.basename(absolute).startsWith('.service-test-')) throw Error('Unsafe test cleanup'); fs.rmSync(absolute, { recursive: true, force: true });
  }
});

